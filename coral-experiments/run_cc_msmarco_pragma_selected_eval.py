"""CC eval at pct_10 budget on the selected MSMARCO pragma sub-lattice cases (GPU).

Reads  data/msmarco_pragma_selected/cc_cases.json  (generated by the local script)
Writes data/msmarco_pragma_selected/cc_results_pct10.json
Resume on case_id.

Two steps:

  Step 1 — run locally first to generate cc_cases.json:
    conda run -n coral python3 run_msmarco_pragma_selected_eval.py

  Step 2 — run on GPU machine (copy cc_cases.json over first):
    VLLM_USE_FLASHINFER_SAMPLER=0 VLLM_WORKER_MULTIPROC_METHOD=spawn \\
      python3 run_cc_msmarco_pragma_selected_eval.py --vllm

  Optionally shard across multiple GPUs:
    CUDA_VISIBLE_DEVICES=0 VLLM_USE_FLASHINFER_SAMPLER=0 VLLM_WORKER_MULTIPROC_METHOD=spawn \\
      python3 run_cc_msmarco_pragma_selected_eval.py --vllm --shard 0 --num-shards 3
    CUDA_VISIBLE_DEVICES=1 ... --shard 1 --num-shards 3
    CUDA_VISIBLE_DEVICES=2 ... --shard 2 --num-shards 3
    python3 run_cc_msmarco_pragma_selected_eval.py --merge
"""
from __future__ import annotations

import argparse
import glob
import json
import os
import time
from collections import defaultdict

from cc_budget_ablation_dev import score_cc
from search.bfs import bfs_search

CC_CASES_PATH  = "data/msmarco_pragma_selected/cc_cases.json"
OUT_PATH       = "data/msmarco_pragma_selected/cc_results_pct10.json"
OUT_PATH_SHARD = "data/msmarco_pragma_selected/cc_results_pct10_shard{}.json"

PCT: int = 10


def _pct_budget(k: int) -> int:
    return max(1, int(2**k * PCT / 100))


# ---------------------------------------------------------------------------
# Merge shards
# ---------------------------------------------------------------------------

def merge_shards() -> None:
    shard_files = sorted(glob.glob(OUT_PATH_SHARD.format("*")))
    if not shard_files:
        print("No shard files found.")
        return
    results: list[dict] = []
    for path in shard_files:
        with open(path) as f:
            shard = json.load(f)
        results.extend(shard)
        print(f"  {path}: {len(shard)} rows")
    results.sort(key=lambda r: r["case_id"])
    with open(OUT_PATH, "w") as f:
        json.dump(results, f, indent=2)
    correct = sum(1 for r in results if r["outcome"] == "correct")
    print(f"\nMerged {len(results)} rows → {OUT_PATH}")
    print(f"Overall acc={correct/len(results):.1%} ({correct}/{len(results)})")
    _print_summary(results)


def _print_summary(results: list[dict]) -> None:
    by_size: dict[int, list[dict]] = defaultdict(list)
    for r in results:
        by_size[r["effective_size"]].append(r)
    print(f"\n{'k':>3}  {'N':>4}  {'Acc':>6}  {'Avg cost':>9}")
    for size in sorted(by_size):
        rows    = by_size[size]
        correct = sum(1 for r in rows if r["outcome"] == "correct")
        cost    = sum(r["calls"] + r["budget"] for r in rows) / len(rows)
        print(f"  {size:>3}  {len(rows):>4}  {correct/len(rows):>5.0%}  {cost:>9.1f}")


# ---------------------------------------------------------------------------
# Run
# ---------------------------------------------------------------------------

def run_eval(shard: int | None, num_shards: int) -> None:
    from load_cc_model import add_model_args, load_model_and_tokenizer
    from search.contextcite import contextcite_search

    parser = argparse.ArgumentParser()
    add_model_args(parser)
    parser.add_argument("--run",        action="store_true")
    parser.add_argument("--shard",      type=int, default=None)
    parser.add_argument("--num-shards", type=int, default=1)
    args = parser.parse_args()

    shard      = args.shard
    num_shards = args.num_shards

    with open(CC_CASES_PATH) as f:
        all_cases = json.load(f)

    if shard is not None:
        cases    = [c for c in all_cases if c["case_id"] % num_shards == shard]
        out_path = OUT_PATH_SHARD.format(shard)
        print(f"Shard {shard}/{num_shards}: {len(cases)} cases (of {len(all_cases)})")
    else:
        cases    = all_cases
        out_path = OUT_PATH
    print(f"Output → {out_path}")

    model, tokenizer = load_model_and_tokenizer(args)

    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    try:
        with open(out_path) as f:
            results: list[dict] = json.load(f)
        done = {r["case_id"] for r in results}
        print(f"Resuming: {len(done)} cases already done")
    except FileNotFoundError:
        results = []
        done    = set()

    skipped = 0
    for case in cases:
        cid    = case["case_id"]
        k      = case["effective_size"]
        budget = _pct_budget(k)

        if cid in done:
            continue

        bfs_res = bfs_search(
            case["criteria"], case["rankings_by_combo"],
            start_node=case["start_node"], direction="down",
        )
        if not bfs_res["found"]:
            skipped += 1
            continue

        print(f"  [c{cid:>3} k={k} b={budget}] qid={case['query_id']} ...", end=" ", flush=True)
        t0 = time.time()
        try:
            cc_res = contextcite_search(
                case["criteria"], case["rankings_by_combo"],
                case["query"], case["sources"], case["plausible_answers"],
                model, tokenizer,
                num_ablations=budget,
                batch_size=args.batch_size,
                start_node=case["start_node"],
                direction="down",
            )
        except Exception as e:
            print(f"ERROR: {e}")
            with open(out_path, "w") as f:
                json.dump(results, f, indent=2)
            raise
        elapsed = time.time() - t0

        scored = score_cc(bfs_res, cc_res, case["rankings_by_combo"], case["start_node"])
        results.append({
            "case_id":        cid,
            "query_id":       case["query_id"],
            "effective_size": k,
            "budget":         budget,
            "bfs_key":        bfs_res["key"],
            "bfs_layer":      bfs_res["size"],
            "bfs_calls":      bfs_res["calls"],
            "elapsed":        round(elapsed, 2),
            **scored,
        })
        done.add(cid)

        tag = "OK" if scored["outcome"] == "correct" else scored["outcome"].upper()
        print(f"{tag} ({elapsed:.1f}s)")

        with open(out_path, "w") as f:
            json.dump(results, f, indent=2)

    if skipped:
        print(f"\nSkipped {skipped} cases (no BFS CF)")
    correct = sum(1 for r in results if r["outcome"] == "correct")
    print(f"\nDone. {len(results)} cases  acc={correct/len(results):.1%}  → {out_path}")
    _print_summary(results)


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--run",        action="store_true")
    parser.add_argument("--merge",      action="store_true")
    parser.add_argument("--vllm",       action="store_true")
    parser.add_argument("--model",      default="meta-llama/Llama-3.1-8B-Instruct")
    parser.add_argument("--batch-size", type=int, default=8)
    parser.add_argument("--shard",      type=int, default=None)
    parser.add_argument("--num-shards", type=int, default=1)
    args = parser.parse_args()

    if args.merge:
        merge_shards()
    elif args.run or args.vllm:
        run_eval(args.shard, args.num_shards)
    else:
        parser.print_help()


if __name__ == "__main__":
    main()
